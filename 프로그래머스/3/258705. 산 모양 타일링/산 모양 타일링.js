function solution(n, tops) {
    const MOD = 10007;
    const m = 2 * n + 1; // 밑변 삼각형 전체 개수 (U0, D0, U1, D1, ... , D(n-1), Un)

    /*
        dp[k] = 1번째 자리부터 k번째 자리까지(1-indexed)를 모두 처리했을 때의 경우의 수.
        1번째 자리는 항상 U0(위쪽 삼각형)이므로 가중치는 무조건 1이다.
        dp[0] = 1은 "아무 자리도 없는 상태"를 나타내는 기준값(빈 경우 1가지)이다.
    */
    const dp = new Array(m + 1);
    dp[0] = 1;
    dp[1] = 1;

    for (let k = 2; k <= m; k++) {
        let weight = 1; // 기본값: U 타입 자리이거나, D 타입인데 봉우리가 없는 경우

        if (k % 2 === 0) {
            /*
            1-indexed에서 짝수 번째 자리는 항상 D타입(아래쪽 삼각형)이다.
            k번째 자리가 D_i에 해당할 때, i = k/2 - 1로 계산된다.
            (예: k=2 -> D0, k=4 -> D1, k=6 -> D2 ...)
            tops[i]가 1이면(봉우리가 붙어있으면), 이 자리가 "혼자"일 때
            (D_i 혼자 + T_i 혼자) 또는 (D_i-T_i 짝짓기) 2가지가 가능하므로 가중치 2를 적용한다.
        */
            const i = k / 2 - 1;
            weight = tops[i] === 1 ? 2 : 1;
        }

        // k번째 자리를 혼자 둔 경우(가중치 적용) + (k-1)번째와 짝지은 경우
        dp[k] = (dp[k - 1] * weight + dp[k - 2]) % MOD;
    }
    return dp[m];
}